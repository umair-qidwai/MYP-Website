/** Regenerate the content migration after changing shared/visitor-content.ts. Never executes SQL. */
import { writeFileSync } from "node:fs";
import { pageDocSchema } from "../../shared/blocks";
import {
  ABOUT_SECTION_SOURCES,
  buildVisitorPages,
  PAGE_EXTRAS,
  PAGE_INTROS,
  reorganizeHome,
  TEAM_PLACEHOLDERS,
  VISITOR_NAVIGATION,
  VISITOR_QUICK_LINKS,
} from "../../shared/visitor-content";

const q = (value: string) => `'${value.replaceAll("'", "''")}'`;
const json = (value: unknown) => q(JSON.stringify(value));
const now = "strftime('%Y-%m-%dT%H:%M:%fZ', 'now')";
const sql: string[] = [
  "-- Generated by npm run content:build-migration. Source: shared/visitor-content.ts.",
  "-- Reorganize existing published content; retain previous drafts and published versions in revisions.",
  "-- Drafts with unpublished staff changes are preserved. Old page URLs and media remain intact.",
  `INSERT INTO revisions (entity_type, entity_id, action, data_json, title, created_at)
SELECT 'page', id, 'save', draft_json, title, ${now} FROM pages
WHERE path IN ('', 'services', 'free-clinic', 'volunteer', 'youth', 'team', 'my-community-cafe', 'climatejustice') AND deleted_at IS NULL;`,
  `INSERT INTO revisions (entity_type, entity_id, action, data_json, title, created_at)
SELECT 'page', id, 'publish', published_json, title, ${now} FROM pages
WHERE path IN ('', 'services', 'free-clinic', 'volunteer', 'youth', 'team', 'my-community-cafe', 'climatejustice') AND published_json IS NOT NULL AND deleted_at IS NULL;`,
];

for (const [key, value] of Object.entries({ navigation: VISITOR_NAVIGATION, quickLinks: VISITOR_QUICK_LINKS })) {
  sql.push(`INSERT INTO revisions (entity_type, entity_id, action, data_json, title, created_at)
SELECT 'setting', key, 'save', value_json, ${q(key)}, ${now} FROM settings WHERE key = ${q(key)};`);
  sql.push(`INSERT INTO settings (key, value_json, updated_at) VALUES (${q(key)}, ${json(value)}, ${now})
ON CONFLICT(key) DO UPDATE SET value_json = excluded.value_json, updated_at = excluded.updated_at;`);
}

for (const [path, seed] of Object.entries(buildVisitorPages())) {
  const doc = pageDocSchema.parse(seed);
  sql.push(`INSERT INTO pages (id, path, title, status, draft_json, published_json, has_changes, published_at, created_at, updated_at)
VALUES (${q(`visitor_${path.replaceAll("/", "_")}`)}, ${q(path)}, ${q(doc.title)}, 'published', ${json(doc)}, ${json(doc)}, 0, ${now}, ${now}, ${now})
ON CONFLICT(path) DO NOTHING;`);
  if (path === "services")
    sql.push(`UPDATE pages SET title = ${q(doc.title)},
draft_json = CASE WHEN has_changes = 0 THEN ${json(doc)} ELSE draft_json END,
published_json = ${json(doc)}, updated_at = ${now}
WHERE path = 'services' AND status = 'published' AND deleted_at IS NULL;`);
}

/** Update both snapshots independently, preserving unsubmitted staff drafts. */
function updateDocument(path: string, expression: (column: string) => string) {
  sql.push(`UPDATE pages SET
draft_json = CASE WHEN has_changes = 0 THEN ${expression("draft_json")} ELSE draft_json END,
published_json = CASE WHEN published_json IS NOT NULL THEN ${expression("published_json")} ELSE NULL END,
updated_at = ${now}
WHERE path = ${q(path)} AND status = 'published' AND deleted_at IS NULL;`);
}

// Insert the new sections among existing blocks, keeping their content and original relative order.
const skeleton = reorganizeHome({ title: "Home", seo: {}, blocks: [] });
const homeBlocks = new Map(skeleton.blocks.map((b) => [b.id, b]));
const injectedIds = [...homeBlocks.keys()];
const heroButtons = [
  { label: "Get Help", href: "/services", style: "primary" },
  { label: "Donate", href: "/donate", style: "secondary" },
  { label: "Volunteer", href: "/volunteer", style: "link" },
];
updateDocument("", (column) => {
  const position = (type: string, fallback: number) =>
    `(coalesce((SELECT CAST(key AS INTEGER) FROM json_each(${column}, '$.blocks') WHERE json_extract(value, '$.type') = '${type}' LIMIT 1), ${fallback}) * 10)`;
  return `json_set(${column}, '$.blocks', json((SELECT json_group_array(json(block)) FROM (
SELECT CASE WHEN json_extract(value, '$.type') = 'hero' THEN json_set(value, '$.buttons', json(${json(heroButtons)})) ELSE value END AS block, CAST(key AS INTEGER) * 10 AS position
FROM json_each(${column}, '$.blocks') WHERE json_extract(value, '$.id') NOT IN (${injectedIds.map(q).join(", ")})
UNION ALL SELECT ${json(homeBlocks.get("visitor-paths"))}, ${position("hero", -1)} + 1
UNION ALL SELECT ${json(homeBlocks.get("home-directory"))}, ${position("programs", 1)} + 1
UNION ALL SELECT ${json(homeBlocks.get("home-service-preview"))}, ${position("programs", 1)} + 2
UNION ALL SELECT ${json(homeBlocks.get("home-enterprises"))}, ${position("stats", 100)} + 1
ORDER BY position
))))`;
});
updateDocument("", (column) => `json_insert(${column}, '$.blocks[#]', json(${json(homeBlocks.get("home-news"))}))`);

for (const [path, intro] of Object.entries(PAGE_INTROS)) {
  updateDocument(
    path,
    (column) => `json_set(${column}, '$.blocks', json((SELECT json_group_array(json(block)) FROM (
SELECT value AS block, CAST(key AS INTEGER) * 10 AS position FROM json_each(${column}, '$.blocks') WHERE json_extract(value, '$.id') != ${q(intro.id)}
UNION ALL SELECT ${json(intro)}, CASE WHEN json_extract(${column}, '$.blocks[0].type') = 'hero' THEN 1 ELSE -1 END
ORDER BY position
))))`,
  );
}
for (const [path, blocks] of Object.entries(PAGE_EXTRAS)) {
  for (const block of blocks)
    updateDocument(
      path,
      (column) =>
        `CASE WHEN EXISTS (SELECT 1 FROM json_each(${column}, '$.blocks') WHERE json_extract(value, '$.id') = ${q(block.id)}) THEN ${column} ELSE json_insert(${column}, '$.blocks[#]', json(${json(block)})) END`,
    );
}
// Keep the sitemap's 11 primary pages, drawing detailed sections from the existing CMS pages.
for (const source of ABOUT_SECTION_SOURCES) {
  updateDocument(
    "about",
    (
      column,
    ) => `CASE WHEN EXISTS (SELECT 1 FROM pages AS original WHERE original.path = ${q(source)} AND original.status = 'published' AND original.deleted_at IS NULL AND original.published_json IS NOT NULL)
THEN json_set(${column}, '$.blocks', json((SELECT json_group_array(json(block)) FROM (
SELECT value AS block FROM json_each(${column}, '$.blocks')
UNION ALL SELECT json_set(value, '$.id', ${q(`about-${source}-`)} || json_extract(value, '$.id')) FROM json_each((SELECT published_json FROM pages AS original WHERE original.path = ${q(source)}), '$.blocks')
)))) ELSE ${column} END`,
  );
}
updateDocument(
  "impact",
  (column) => `json_set(${column}, '$.blocks', json((SELECT json_group_array(json(block)) FROM (
SELECT value AS block FROM json_each(${column}, '$.blocks')
UNION ALL SELECT json_set(value, '$.id', 'impact-highlights') FROM json_each((SELECT published_json FROM pages AS original WHERE original.path = '' AND original.status = 'published' AND original.deleted_at IS NULL), '$.blocks') WHERE json_extract(value, '$.type') = 'stats'
))))`,
);
for (const [path, title] of [
  ["youth", "Youth & Family Programs"],
  ["my-community-cafe", "MY Community Café & Catering"],
]) {
  updateDocument(path, (column) => `json_set(${column}, '$.title', ${q(title)})`);
  sql.push(`UPDATE pages SET title = ${q(title)} WHERE path = ${q(path)} AND status = 'published' AND deleted_at IS NULL;`);
}
updateDocument(
  "free-clinic",
  (column) =>
    `json_set(replace(${column}, ${q("We are located at 3725 Sullivant Avenue, Columbus, OH, 43204 at the MY Project USA Center.")}, ${q("Please confirm your visit location with the clinic team before travelling.")}), '$.title', 'Hilltop Free Clinic', '$.hideTitle', json('false'))`,
);
sql.push(`UPDATE pages SET title = 'Hilltop Free Clinic' WHERE path = 'free-clinic' AND status = 'published' AND deleted_at IS NULL;`);
updateDocument(
  "team",
  (column) =>
    `CASE WHEN EXISTS (SELECT 1 FROM json_each(${column}, '$.blocks') WHERE json_extract(value, '$.id') = 'team-profiles') THEN ${column} ELSE json_insert(${column}, '$.blocks[#]', json(${json(TEAM_PLACEHOLDERS)})) END`,
);

sql.push(
  `UPDATE settings SET value_json = json_set(value_json, '$.items', json((SELECT json_group_array(json(CASE WHEN json_extract(value, '$.name') = 'MY Family Pantry' THEN json_set(value, '$.href', '/services#option-get-help-0') ELSE value END)) FROM json_each(settings.value_json, '$.items')))), updated_at = ${now} WHERE key = 'programs';`,
);
for (const [from, to] of [
  ["/get-help", "/services"],
  ["/programs", "/services#section-program-directory"],
  ["/program-directory", "/services#section-program-directory"],
  ["/food-pantry", "/services#option-get-help-0"],
  ["/free-clinic/request", "/services#section-clinic-request"],
  ["/pathways", "/services#option-get-help-3"],
  ["/contact", "/contacts"],
  ["/cafe", "/my-community-cafe"],
]) {
  sql.push(
    `INSERT INTO redirects (from_path, to_path, status_code, source, created_at) VALUES (${q(from)}, ${q(to)}, 301, 'manual', ${now}) ON CONFLICT(from_path) DO NOTHING;`,
  );
}

writeFileSync("migrations/0005_visitor_navigation.sql", sql.join("\n\n") + "\n");
console.log("Generated migrations/0005_visitor_navigation.sql. No database was changed.");
