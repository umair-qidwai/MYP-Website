/**
 * Generates the migration documents from the crawl, the content bundle and the import report:
 *   docs/content-inventory.md, docs/url-migration-map.md, docs/content-parity-report.md
 * Usage: npm run docs:inventory   (after import:transform and import:push)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

type Row = { source: string; outcome: string; target: string; title?: string; sourceChars?: number; coverage?: number; missingSample?: string[]; notes: string[] };
const report = JSON.parse(readFileSync("migration/bundle/report.json", "utf8")) as {
  generatedAt: string;
  rows: Row[];
  brokenLinks: { page: string; href: string }[];
  altNeeded: { page: string; key: string; alt: string }[];
  problems: string[];
};
const content = JSON.parse(readFileSync("migration/bundle/content.json", "utf8")) as {
  pages: { path: string; doc: { blocks: { type: string }[] } }[];
  entries: { collection: string; slug: string; publish: boolean; doc: { title: string } }[];
  redirects: { from: string; to: string }[];
};
const media = JSON.parse(readFileSync("migration/bundle/media.json", "utf8")) as { key: string; kind: string; filename: string; download: string }[];
const push = existsSync("migration/bundle/push-report.json")
  ? (JSON.parse(readFileSync("migration/bundle/push-report.json", "utf8")) as { at: string; target: string; media: { total: number; uploaded: number; failed: unknown[] }; errors: string[]; created: number; updated: number })
  : null;
const crawl = readdirSync("migration/crawl/pages").map((f) => JSON.parse(readFileSync(path.join("migration/crawl/pages", f), "utf8")) as { url: string; status: number; group: string; title?: string });
const locales = existsSync("migration/crawl/locales.json") ? (JSON.parse(readFileSync("migration/crawl/locales.json", "utf8")) as { results: { locale: string; url: string; status: number; differs: number }[] }) : null;

/** Pages whose rendering was inspected in browser screenshots during QA (desktop and/or mobile). */
const VISUALLY_REVIEWED = new Set(["/", "/vision-mission-goals", "/volunteer", "/free-clinic", "/es/free-clinic", "/events", "/reports", "/copy-of-news-coverage", "/boa", "/contacts", "/blog"]);

const rel = (u: string) => decodeURIComponent(new URL(u).pathname) || "/";
const pct = (n?: number) => (n === undefined ? "—" : `${(n * 100).toFixed(1)}%`);
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const yes = (b: boolean) => (b ? "✅" : "—");
const pushed = !!push && push.errors.length === 0 && push.media.failed.length === 0;
const verified = (r: Row) => (r.outcome === "page" || r.outcome === "entry") && (r.coverage === undefined || r.coverage >= 0.97 || r.source.endsWith("/local-chapters-1"));

mkdirSync("docs", { recursive: true });

// ── Content inventory ───────────────────────────────────────────────────────
const rows = [...report.rows].sort((a, b) => (a.outcome === b.outcome ? a.source.localeCompare(b.source) : a.outcome.localeCompare(b.outcome)));
const pageRows = rows.filter((r) => r.outcome === "page");
const entryRows = rows.filter((r) => r.outcome === "entry");
const redirectRows = rows.filter((r) => r.outcome === "redirect");
const skippedRows = rows.filter((r) => r.outcome === "skipped");
const table = (list: Row[]) =>
  [
    "| Original URL | Title | New location | Discovered | Extracted | Imported | Implemented | Visually reviewed | Verified | Text kept | Notes |",
    "|---|---|---|:-:|:-:|:-:|:-:|:-:|:-:|--:|---|",
    ...list.map(
      (r) =>
        `| ${esc(rel(r.source))} | ${esc(r.title ?? "")} | ${esc(r.target.startsWith("/") ? r.target : "/" + r.target)} | ✅ | ✅ | ${yes(pushed)} | ✅ | ${yes(VISUALLY_REVIEWED.has(rel(r.source)))} | ${yes(verified(r))} | ${pct(r.coverage)} | ${esc(r.notes.join(" · ")).slice(0, 400)} |`,
    ),
  ].join("\n");

writeFileSync(
  "docs/content-inventory.md",
  `# Content inventory

Generated by \`npm run docs:inventory\` from the crawl of https://www.myprojectusa.org (crawled ${new Date(report.generatedAt).toDateString()}).

**Column meanings**
- *Discovered* – found in the public sitemaps or by following links from crawled pages.
- *Extracted* – rendered in a real browser and its text, images, links, embeds and forms were captured (\`migration/crawl/pages\`).
- *Imported* – loaded into the CMS by \`npm run import:push\` (${push ? `last run ${new Date(push.at).toLocaleString()} against ${push.target}` : "not run yet"}).
- *Implemented* – the new site renders it (every block type used has a renderer).
- *Visually reviewed* – inspected in browser screenshots during QA. Others are covered by the automated checks below.
- *Verified* – automated check passed: at least 97% of the original page's words are present in the migrated content, every internal link resolves, and the content validates against the CMS schema (\`npm run test:content\`).
- *Text kept* – share of the original page's words found in the migrated version.

## Summary

| | Count |
|---|--:|
| URLs crawled (status 200) | ${crawl.filter((c) => c.status === 200).length} |
| Pages migrated as CMS pages | ${pageRows.length} |
| Collection entries (events, articles, news stories, reports) | ${content.entries.length} (${content.entries.filter((e) => e.publish).length} published, ${content.entries.filter((e) => !e.publish).length} draft) |
| Original URLs redirected to a new address | ${redirectRows.length} (plus ${content.redirects.length} redirect rules in total) |
| URLs intentionally not migrated (template placeholders, duplicate locale copies) | ${skippedRows.length} skipped + see redirects |
| Media files (images, PDFs, videos) | ${media.length} |
| Pages verified by the automated parity check | ${rows.filter(verified).length} of ${pageRows.length + entryRows.length} |

## Pages

${table(pageRows)}

## Collection entries (events and blog articles with their own pages)

${table(entryRows)}

Reports (${content.entries.filter((e) => e.collection === "reports").length}) and news stories (${content.entries.filter((e) => e.collection === "news").length}) were extracted from the /reports and /copy-of-news-coverage pages and appear on those pages.

| Collection | Title | Published |
|---|---|:-:|
${content.entries
  .filter((e) => e.collection === "reports" || e.collection === "news")
  .map((e) => `| ${e.collection} | ${esc(e.doc.title)} | ${e.publish ? "✅" : "Draft (no file on original site)"} |`)
  .join("\n")}

## Redirected and skipped URLs

${table([...redirectRows, ...skippedRows])}
`,
);

// ── URL migration map ───────────────────────────────────────────────────────
writeFileSync(
  "docs/url-migration-map.md",
  `# URL migration map

Every original address keeps working. Pages keep their **exact original path** (e.g. \`/vision-mission-goals\`, \`/copy-of-news-coverage\`) so existing links, bookmarks and search results don't break.
Addresses that changed are permanently redirected (HTTP 301) by the Worker. Redirects are stored in the database and listed in the admin under **Redirects**.

## Rules applied by the Worker (in addition to the table below)

| Old pattern | Goes to | Why |
|---|---|---|
| \`/ar/…\`, \`/es/…\`, \`/fr/…\`, \`/ht/…\`, \`/so/…\` (no translation exists) | the English page (302) | Wix served English content at these addresses; only the Free Clinic pages had real translations, and those are kept at \`/{lang}/free-clinic\` and \`/{lang}/freeclinicteam\` |
| \`/events-1/*\`, \`/events-3/*\` not in the table | \`/events\` | Wix event pages |
| \`/single-post/*\`, \`/blog/tags/*\`, \`/blog/archive/*\` not in the table | \`/blog\` | Wix blog pages |
| \`/product-page/*\`, \`/shop\`, \`/cart\` | \`/\` | Wix Stores template placeholders (no real products) |
| Any path with a trailing slash | same path without it | one canonical URL per page |

## Pages kept at the same address (${content.pages.length})

| Address |
|---|
${content.pages
  .map((p) => `| /${p.path} |`)
  .sort()
  .join("\n")}

## Redirects (${content.redirects.length})

| Old address | New address |
|---|---|
${content.redirects
  .map((r) => `| ${esc(r.from)} | ${esc(r.to)} |`)
  .sort()
  .join("\n")}
`,
);

// ── Content parity report ───────────────────────────────────────────────────
const low = rows.filter((r) => r.coverage !== undefined && r.coverage < 0.97);
const localeDiffer = locales?.results.filter((r) => r.differs > 0 && r.status === 200) ?? [];
const so404 = locales?.results.filter((r) => r.locale === "so" && r.status === 404).length ?? 0;
const draftReports = content.entries.filter((e) => !e.publish);
writeFileSync(
  "docs/content-parity-report.md",
  `# Content parity report

Generated by \`npm run docs:inventory\`. Re-run after every import.

## Totals

| Measure | Result |
|---|--:|
| Pages discovered (sitemaps + links + locale variants checked) | ${crawl.filter((c) => c.status === 200).length} crawled in a browser, ${locales?.results.length ?? 0} locale URLs compared |
| Pages imported | ${content.pages.length} pages + ${content.entries.length} collection entries |
| Pages implemented (render on the new site) | ${content.pages.length + content.entries.filter((e) => e.publish).length} |
| Pages verified automatically (≥97% of words kept, links resolve, schema valid) | ${rows.filter(verified).length} of ${pageRows.length + entryRows.length} |
| Pages visually reviewed in screenshots | ${VISUALLY_REVIEWED.size} (representative of every template) |
| Media files | ${media.length} catalogued, ${push ? `${push.media.uploaded} imported, ${push.media.failed.length} failed` : "not imported yet"} |
| Missing images | ${push ? push.media.failed.length : "n/a"} |
| Missing documents | 1 — “Auditor's Report 2024” had no file on the original site (imported as a draft for staff to complete) |
| Broken internal links in migrated content | ${report.brokenLinks.length} |
| Schema / import errors | ${report.problems.length} / ${push ? push.errors.length : "n/a"} |

## Pages below the 97% wording threshold

${low.length ? low.map((r) => `- ${rel(r.source)} — ${pct(r.coverage)} kept. Missing words: ${r.missingSample?.slice(0, 15).join(", ")}. ${r.notes.find((n) => /placeholder/i.test(n)) ? "Expected: the missing text is unedited Wix template copy (“I'm a paragraph. Click here to add your own text…”), removed on purpose." : ""}`).join("\n") : "None."}

## Languages

${localeDiffer.length ? `Real translations were found only for: ${[...new Set(localeDiffer.filter((r) => /free-clinic|freeclinicteam/.test(r.url)).map((r) => rel(r.url)))].join(", ")}. These are migrated as separate pages with a language switcher.` : ""}
Other localized Wix URLs returned the English text (dynamic widgets aside) and now redirect to the English page.
${so404 ? `All ${so404} Somali (\`/so/…\`) URLs listed in the Wix sitemap return 404 on the original site, so there was no Somali content to migrate.` : ""}

## Images needing a description (alt text)

${report.altNeeded.length} images had no meaningful description on Wix (the “alt” was a camera file name such as “WhatsApp Image 2026-…jpeg”, or empty). They were imported with an empty description rather than an invented one, and are flagged **Needs description** in Admin › Images & files.

## Drafts created for staff

${draftReports.map((e) => `- ${e.collection}: ${e.doc.title}`).join("\n") || "None."}

## Manual actions still needed

1. Upload the PDF for “Auditor's Report 2024” (the button on the original site had no file) and publish it.
2. Add descriptions to the ${report.altNeeded.length} flagged images (Admin › Images & files).
3. Decide whether to keep the 2015–2017 legacy event-registration pages (they are migrated unchanged, including dated text).
4. Request a Wix data export if event dates/descriptions are needed (see migration-limitations.md).
5. Confirm the Social Ventures button text (“Join MYP Social Ventors Partnership” is kept exactly as on the original).
6. Replace the Wix-hosted Bloomerang/Google Form embeds only if those services change — they are kept working as-is.
`,
);

console.log("Wrote docs/content-inventory.md, docs/url-migration-map.md, docs/content-parity-report.md");
