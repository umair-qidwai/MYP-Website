import { chromium } from "playwright";
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on("pageerror", (e) => console.log("PAGEERROR", (e.stack ?? String(e)).slice(0, 1500)));
await p.goto("http://localhost:5180/admin/login", { waitUntil: "load" });
await p.waitForTimeout(1500);
await p.getByLabel("Email").fill("qa-admin@example.org");
await p.getByLabel("Password").fill("Correct-Horse-Battery-42");
await p.waitForTimeout(2500);
await p.getByRole("button", { name: "Sign in" }).click();
await p.waitForTimeout(2500);
await p.goto("http://localhost:5180/admin/pages", { waitUntil: "networkidle" });
await p.getByRole("button", { name: "New page" }).click();
await p.getByLabel("Page title").fill("Debug Page " + Date.now());
await p.getByRole("button", { name: "Create page" }).click();
await p.waitForTimeout(2500);
await p.getByRole("button", { name: "Add a section" }).last().click();
await p.getByRole("dialog", { name: "Add a section" }).getByRole("button", { name: /^Text/ }).click();
await p.waitForTimeout(2000);
await p.screenshot({ path: "qa/screens/debug-add.png" });
console.log(await p.evaluate(() => [...document.querySelectorAll(".ProseMirror,[contenteditable]")].map((e) => e.outerHTML.slice(0, 300))));
await p.getByRole("textbox", { name: "Text" }).click().catch((e) => console.log("CLICK FAIL", String(e).slice(0, 200)));
await p.keyboard.type("Hello");
await p.waitForTimeout(1000);
await b.close();
